/**
 * Read the token build (`packages/tokens/dist`). Nothing in the WordPress themes is typed by hand:
 * colours, sizes and radii come from these files.
 */
import { readFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);

export const TOKENS_DIST = dirname(require.resolve("@salon-demos/tokens/tokens.css"));

export const NOTICE = "Generated by wordpress/scripts/build-theme-assets.mjs. Do not edit by hand.";

/** Read one file from the token build. */
export const readDist = (file) => readFile(join(TOKENS_DIST, file), "utf8");

/** Read `--name: value;` declarations from one selector block of tokens.css. */
export function readBlock(css, selector) {
  const start = css.indexOf(`${selector} {`);
  if (start === -1) throw new Error(`tokens.css has no "${selector}" block`);
  const body = css.slice(start, css.indexOf("}", start));
  const vars = {};
  for (const [, name, value] of body.matchAll(/--([\w-]+):\s*([^;]+);/g)) vars[name] = value.trim();
  return vars;
}

/** Variables of the group `:root` block with one brand's overrides applied. */
export function brandVars(css, brand) {
  return { ...readBlock(css, ":root"), ...readBlock(css, `[data-brand="${brand}"]`) };
}

/** Resolve a token name whose value is a `var(--x)` chain to a literal value. */
export function resolver(vars) {
  const resolve = (value, depth = 0) => {
    if (depth > 10) throw new Error(`Token reference loop at ${value}`);
    const match = /^var\(--([\w-]+)\)$/.exec(value);
    if (!match) return value;
    const next = vars[match[1]];
    if (next === undefined) throw new Error(`Unknown token --${match[1]}`);
    return resolve(next, depth + 1);
  };
  return (name) => resolve(`var(--${name})`);
}

/**
 * Replace every fallback-less `var(--x)` inside a value with its literal value, recursively.
 * References with a fallback (`var(--font-body, "DM Sans")`) are hooks and stay as they are.
 */
export function inlineRefs(vars, value, depth = 0) {
  if (depth > 10) throw new Error(`Token reference loop at ${value}`);
  const next = value.replace(/var\(--([\w-]+)\)/g, (whole, name) => vars[name] ?? whole);
  return next === value ? value : inlineRefs(vars, next, depth + 1);
}
