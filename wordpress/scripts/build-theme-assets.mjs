/**
 * Copies generated design tokens and self-hosted fonts into the Sable & Shear child theme.
 *
 *   packages/tokens/dist/tokens.css          -> assets/build/tokens.css
 *   packages/tokens/dist/elementor-kit.json  -> assets/build/elementor-kit/site-settings.json
 *                                               (+ Theme Style settings, manifest.json and a
 *                                               ready-to-import sable-shear-kit.zip)
 *   @fontsource WOFF2 (Latin subset)         -> assets/build/fonts/*.woff2 + fonts.css
 *
 * Output is git-ignored (`build/`), rebuilt by `pnpm build` (Turborepo runs the tokens build
 * first because this package depends on it) and shipped by the FTP deploy workflow.
 * Nothing here is typed by hand: colours, sizes and radii are read from the token build.
 */
import { copyFile, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { crc32 } from "node:zlib";
import { createFontStack } from "@capsizecss/core";
import arial from "@capsizecss/metrics/arial";
import cormorantGaramond from "@capsizecss/metrics/cormorantGaramond";
import georgia from "@capsizecss/metrics/georgia";
import manrope from "@capsizecss/metrics/manrope";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);

const THEME = join(here, "..", "themes", "sable-hello-child");
const OUT = join(THEME, "assets", "build");
const TOKENS_DIST = dirname(require.resolve("@salon-demos/tokens/tokens.css"));

const NOTICE = "Generated by wordpress/scripts/build-theme-assets.mjs. Do not edit by hand.";

/** Latin + common punctuation, as in design brief 2.5. */
const UNICODE_RANGE =
  "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+2000-206F, U+20AC, U+2122, U+2212";

/**
 * Self-hosted faces. `preload` marks the two files the theme preloads (body regular and the
 * hero display weight, brief 2.5 rule 4). Decorative italic uses `optional` (brief 2.5 rule 3).
 */
