/** Quote a font family name for CSS when it has spaces, digits or symbols (generic families stay bare). */
export function quoteFamily(name) {
  return /^[A-Za-z-]+$/.test(name) ? name : `"${name}"`;
}

/** `"DM Sans, system-ui, sans-serif"` (or an array) -> `["DM Sans", "system-ui", "sans-serif"]` */
export function fontFamilies(stack) {
  const list = Array.isArray(stack) ? stack : String(stack).split(",");
  return list.map((f) => f.trim().replace(/^["']|["']$/g, "")).filter(Boolean);
}

/** `"DM Sans, system-ui, sans-serif"` -> `"DM Sans", system-ui, sans-serif` */
export function fontStack(stack) {
  return fontFamilies(stack).map(quoteFamily).join(", ");
}

/** Token value as authored, before transforms (DTCG `$value` or legacy `value`). */
export function originalValue(token) {
  return token.original.$value ?? token.original.value;
}

/** True when the token's authored value references the brand ink (shadows). */
export function usesBrandInk(token) {
  const value = originalValue(token);
  return typeof value === "string" && value.includes("{brand.ink-rgb}");
}

/** Find a resolved token by its dot path, e.g. `color.action.bg`. Throws if missing. */
export function getToken(dictionary, path) {
  const token = dictionary.allTokens.find((t) => t.path.join(".") === path);
  if (!token) throw new Error(`Token not found: ${path}`);
  return token;
}

/** Resolved (transformed) value of a token. DTCG tokens keep it in `$value`. */
export function tokenValue(token) {
  return token.$value ?? token.value;
}

/** Shorthand for the resolved value of a token path. */
export function value(dictionary, path) {
  return tokenValue(getToken(dictionary, path));
}

/** Per-breakpoint pixel sizes stored on font-size tokens. */
export function pxSizes(dictionary, path) {
  const ext = getToken(dictionary, path).$extensions?.["com.orrin.px"];
  if (!ext) throw new Error(`No com.orrin.px extension on ${path}`);
  return ext;
}

